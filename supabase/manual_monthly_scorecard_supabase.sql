-- ===========================================================================
-- Manual Monthly Scorecard Management System - Supabase Complete Script
-- Target: Supabase PostgreSQL (SQL Editor)
--
-- Features:
--   1. Ensures pgcrypto extension is enabled.
--   2. Creates public.teams and public.users if they don't already exist.
--   3. Bridges application users to Supabase Auth (auth.users).
--   4. Creates manual_scorecards, manual_scorecard_periods,
--      manual_scorecard_customers, and scorecard_audit_logs.
--   5. Sets up auto updated_at triggers and enables Row Level Security (RLS).
--   6. INSERTS complete sample data (Teams, Auth Users, Users, Scorecards,
--      Weekly Periods 1-5, Targets, Customer Collection Plan, and Audit Logs).
--
-- How to run:
--   Open Supabase Dashboard -> SQL Editor -> New Query -> Paste all -> Click Run.
-- ===========================================================================

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ---------------------------------------------------------------------------
-- 1. Base Tables: public.teams and public.users (created if not present)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.teams (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    code VARCHAR(20) NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id VARCHAR(8) UNIQUE,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    designation VARCHAR(100),
    team_id INTEGER REFERENCES public.teams(id) ON DELETE SET NULL,
    reporting_manager_id INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'EMPLOYEE' CHECK (role IN ('ADMIN', 'TL', 'CO', 'EMPLOYEE')),
    password_hash VARCHAR(255),
    auth_user_id UUID,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Ensure auth_user_id column exists
ALTER TABLE public.users
    ADD COLUMN IF NOT EXISTS auth_user_id UUID;

-- Link application users to Supabase Auth
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_users_auth_user_id'
          AND conrelid = 'public.users'::regclass
    ) THEN
        ALTER TABLE public.users
            ADD CONSTRAINT fk_users_auth_user_id
            FOREIGN KEY (auth_user_id)
            REFERENCES auth.users(id)
            ON DELETE SET NULL;
    END IF;
END;
$$;

-- Allow nullable password_hash as Supabase Auth becomes authoritative
ALTER TABLE public.users
    ALTER COLUMN password_hash DROP NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_users_auth_user_id
    ON public.users(auth_user_id)
    WHERE auth_user_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS ix_users_reporting_manager_id
    ON public.users(reporting_manager_id);

CREATE INDEX IF NOT EXISTS ix_users_team_id
    ON public.users(team_id);

-- ---------------------------------------------------------------------------
-- 2. Scorecard Header Table
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.manual_scorecards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL
        REFERENCES public.users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    month DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'CLOSED')),
    planned_leave NUMERIC(5, 2) NOT NULL DEFAULT 0 CHECK (planned_leave >= 0),
    unauthorized_leave NUMERIC(5, 2) NOT NULL DEFAULT 0 CHECK (unauthorized_leave >= 0),
    working_days NUMERIC(5, 2) NOT NULL DEFAULT 0 CHECK (working_days >= 0),
    prediction_amount NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (prediction_amount >= 0),

    sheet_score NUMERIC(7,2)
        CHECK (sheet_score IS NULL OR sheet_score >= 0),
    call_score NUMERIC(7,2)
        CHECK (call_score IS NULL OR call_score >= 0),
    marking NUMERIC(5,2)
        CHECK (marking IS NULL OR (marking >= 0 AND marking <= 100)),
    supervisor_notes TEXT,

    -- EMI Portfolio Snapshot
    emi_due_monthly NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (emi_due_monthly >= 0),
    emi_client_count INTEGER NOT NULL DEFAULT 0 CHECK (emi_client_count >= 0),
    emi_hold_count INTEGER NOT NULL DEFAULT 0 CHECK (emi_hold_count >= 0),
    emi_cancel_count INTEGER NOT NULL DEFAULT 0 CHECK (emi_cancel_count >= 0),

    -- TB Portfolio Snapshot
    tb_due_amount NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (tb_due_amount >= 0),
    tb_client_count INTEGER NOT NULL DEFAULT 0 CHECK (tb_client_count >= 0),
    tb_share_count INTEGER NOT NULL DEFAULT 0 CHECK (tb_share_count >= 0),
    tb_hold_count INTEGER NOT NULL DEFAULT 0 CHECK (tb_hold_count >= 0),
    tb_cancel_count INTEGER NOT NULL DEFAULT 0 CHECK (tb_cancel_count >= 0),

    created_by_id INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
    updated_by_id INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
    submitted_at TIMESTAMPTZ,
    submitted_by_id INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
    approved_at TIMESTAMPTZ,
    approved_by_id INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
    closed_at TIMESTAMPTZ,
    closed_by_id INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_manual_scorecard_employee_month UNIQUE (employee_id, month),
    CONSTRAINT ck_manual_scorecard_month_first_day
        CHECK (EXTRACT(DAY FROM month) = 1)
);

CREATE INDEX IF NOT EXISTS ix_manual_scorecards_month
    ON public.manual_scorecards(month);
CREATE INDEX IF NOT EXISTS ix_manual_scorecards_status
    ON public.manual_scorecards(status);
CREATE INDEX IF NOT EXISTS ix_manual_scorecards_employee_status
    ON public.manual_scorecards(employee_id, status);

-- ---------------------------------------------------------------------------
-- 3. Period Performance Rows (0 = Monthly Target, 1..5 = Weekly Periods)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.manual_scorecard_periods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scorecard_id BIGINT NOT NULL
        REFERENCES public.manual_scorecards(id) ON DELETE CASCADE,
    period_index SMALLINT NOT NULL CHECK (period_index BETWEEN 0 AND 5),

    -- Financial collection figures (BDT)
    new_sales NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (new_sales >= 0),
    tb_amount NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (tb_amount >= 0),
    emi_amount NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (emi_amount >= 0),
    total_collection NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (total_collection >= 0),
    total_collection_override NUMERIC(15,2)
        CHECK (total_collection_override IS NULL OR total_collection_override >= 0),

    -- Lead pipeline
    total_leads INTEGER NOT NULL DEFAULT 0 CHECK (total_leads >= 0),
    fair_leads INTEGER NOT NULL DEFAULT 0 CHECK (fair_leads >= 0),
    fb_leads INTEGER NOT NULL DEFAULT 0 CHECK (fb_leads >= 0),
    hp INTEGER NOT NULL DEFAULT 0 CHECK (hp >= 0),
    p INTEGER NOT NULL DEFAULT 0 CHECK (p >= 0),
    fup INTEGER NOT NULL DEFAULT 0 CHECK (fup >= 0),

    -- Activity metrics
    dialed_calls INTEGER NOT NULL DEFAULT 0 CHECK (dialed_calls >= 0),
    connected_calls INTEGER NOT NULL DEFAULT 0 CHECK (connected_calls >= 0),
    outdoor_visits INTEGER NOT NULL DEFAULT 0 CHECK (outdoor_visits >= 0),
    indoor_cx INTEGER NOT NULL DEFAULT 0 CHECK (indoor_cx >= 0),
    meeting_hours NUMERIC(8,2) NOT NULL DEFAULT 0 CHECK (meeting_hours >= 0),

    -- Optional manual override for monthly achieved
    total_achieved_override NUMERIC(15,2)
        CHECK (total_achieved_override IS NULL OR total_achieved_override >= 0),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_manual_scorecard_period UNIQUE (scorecard_id, period_index)
);

CREATE INDEX IF NOT EXISTS ix_manual_scorecard_periods_scorecard
    ON public.manual_scorecard_periods(scorecard_id);

-- ---------------------------------------------------------------------------
-- 4. Customer Collection Plan
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.manual_scorecard_customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scorecard_id BIGINT NOT NULL
        REFERENCES public.manual_scorecards(id) ON DELETE CASCADE,

    customer_name VARCHAR(255) NOT NULL
        CHECK (length(trim(customer_name)) > 0),
    paid_amount NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (paid_amount >= 0),
    unpaid_amount NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (unpaid_amount >= 0),
    collection_date DATE,
    date_1 DATE,
    date_2 DATE,
    in_out_plan VARCHAR(100),

    new_sales_amount NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (new_sales_amount >= 0),
    tb_amount NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (tb_amount >= 0),
    emi_amount NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (emi_amount >= 0),
    total_collection NUMERIC(15,2)
        GENERATED ALWAYS AS (new_sales_amount + tb_amount + emi_amount) STORED,

    lead_status VARCHAR(10) NOT NULL DEFAULT 'NI'
        CHECK (lead_status IN ('HP', 'P', 'FUP', 'NI')),
    collection_probability SMALLINT NOT NULL DEFAULT 10
        CHECK (collection_probability BETWEEN 10 AND 100),
    remarks TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_manual_scorecard_customers_scorecard
    ON public.manual_scorecard_customers(scorecard_id);
CREATE INDEX IF NOT EXISTS ix_manual_scorecard_customers_collection_date
    ON public.manual_scorecard_customers(collection_date);
CREATE INDEX IF NOT EXISTS ix_manual_scorecard_customers_lead_status
    ON public.manual_scorecard_customers(lead_status);

-- ---------------------------------------------------------------------------
-- 5. Audit Log Table
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.scorecard_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scorecard_id BIGINT
        REFERENCES public.manual_scorecards(id) ON DELETE SET NULL,
    actor_user_id INTEGER
        REFERENCES public.users(id) ON DELETE SET NULL,
    action VARCHAR(60) NOT NULL,
    entity_type VARCHAR(60),
    entity_id BIGINT,
    old_values JSONB,
    new_values JSONB,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_scorecard_audit_logs_scorecard
    ON public.scorecard_audit_logs(scorecard_id);
CREATE INDEX IF NOT EXISTS ix_scorecard_audit_logs_actor
    ON public.scorecard_audit_logs(actor_user_id);
CREATE INDEX IF NOT EXISTS ix_scorecard_audit_logs_created
    ON public.scorecard_audit_logs(created_at DESC);

-- ---------------------------------------------------------------------------
-- 6. Trigger for updated_at timestamps
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.set_manual_scorecard_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_manual_scorecards_updated_at ON public.manual_scorecards;
CREATE TRIGGER trg_manual_scorecards_updated_at
    BEFORE UPDATE ON public.manual_scorecards
    FOR EACH ROW EXECUTE FUNCTION public.set_manual_scorecard_updated_at();

DROP TRIGGER IF EXISTS trg_manual_scorecard_periods_updated_at ON public.manual_scorecard_periods;
CREATE TRIGGER trg_manual_scorecard_periods_updated_at
    BEFORE UPDATE ON public.manual_scorecard_periods
    FOR EACH ROW EXECUTE FUNCTION public.set_manual_scorecard_updated_at();

DROP TRIGGER IF EXISTS trg_manual_scorecard_customers_updated_at ON public.manual_scorecard_customers;
CREATE TRIGGER trg_manual_scorecard_customers_updated_at
    BEFORE UPDATE ON public.manual_scorecard_customers
    FOR EACH ROW EXECUTE FUNCTION public.set_manual_scorecard_updated_at();

